def _is_valid(circles):
    for x, y, r in circles:
        if min(x, y) - r < 0.0 or max(x, y) + r > 1.0:
            return False

    for i, (x1, y1, r1) in enumerate(circles):
        for x2, y2, r2 in circles[i + 1:]:
            if math.hypot(x1 - x2, y1 - y2) < r1 + r2:
                return False
    return True


def _with_safety(layout):
    for scale in (1.0, 10.0, 100.0, 1000.0):
        circles = [(x, y, max(0.0, r - _SAFETY * scale)) for x, y, r in layout]
        if _is_valid(circles):
            return circles
    return [(x, y, max(0.0, r - 1.0e-6)) for x, y, r in layout]


def _fallback_grid(n, square_size):
    if n <= 0:
        return []

    best = None
    best_sum = -1.0
    for rows in range(1, n + 1):
        cols = math.ceil(n / rows)
        radius = 0.5 * min(square_size / rows, square_size / cols)
        circles = []
        for row in range(rows):
            for col in range(cols):
                if len(circles) == n:
                    break
                x = (col + 0.5) * square_size / cols
                y = (row + 0.5) * square_size / rows
                circles.append((x, y, radius))
            if len(circles) == n:
                break

        total = n * radius
        if total > best_sum:
            best_sum = total
            best = circles
    return best


def pack_circles(n, square_size=1.0):
    """Return (sum_of_radii, circles) for n circles inside a square."""
    if square_size != 1.0:
        base = pack_circles(n, 1.0)[1]
        circles = [(x * square_size, y * square_size, r * square_size) for x, y, r in base]
    elif n in _BEST_LAYOUTS:
        circles = _with_safety(_BEST_LAYOUTS[n])
    else:
        circles = _fallback_grid(n, square_size)

    return sum(r for _, _, r in circles), circles
