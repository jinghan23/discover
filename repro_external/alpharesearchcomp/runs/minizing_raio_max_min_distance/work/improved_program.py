def _fit_unit_box(points):
    """Translate and uniformly scale a construction into [0, 1]^d."""
    points = np.array(points, dtype=float, copy=True)
    points -= points.min(axis=0)
    span = points.max(axis=0).max()
    if span > 0.0:
        points /= span
    return points


def _ratio_squared(points):
    distances = pdist(points)
    return float((distances.min() / distances.max()) ** 2)


def _fallback_grid(n, d):
    side = int(np.ceil(n ** (1.0 / d)))
    axes = [np.linspace(0.0, 1.0, side) for _ in range(d)]
    mesh = np.array(np.meshgrid(*axes, indexing="ij")).reshape(d, -1).T
    return mesh[:n]


